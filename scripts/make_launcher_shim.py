"""Build the OmniForge desktop launcher for the bootstrap installer.

Reality check (measured, not assumed)
-------------------------------------
An "OmniForge.exe" cannot be produced by *copying* `python.exe`/`pythonw.exe`: both are real
interpreter images (no `#!` launcher stub), so a copy would just start an empty interpreter and
exit. The three honest ways to get a launcher are:

===============  ================================================  =====================
option           how                                               cost
===============  ================================================  =====================
A. venvlauncher  copy CPython's official ``venvlauncher.exe`` and    0 extra MB, no toolchain
                 retarget it the way ``venv`` does (append the
                 launcher block: interpreter path + script + args)
B. PyInstaller   ``build_exe.bat --onedir`` then compile with         0 extra MB at install
                 ``/DLaunchMode=exe``                                 time (build machine)
C. .cmd / .lnk   ship ``OmniForge.cmd`` and a shortcut that calls     0 MB, console flash
                 ``runtime\\python\\python.exe omniforge.py``            (not a real app exe)
===============  ================================================  =====================

This script implements **A** (fully offline, verified structurally) and always emits **C** as a
fallback, so the installer can ship something bootable either way. It refuses to fake it: the
old "copy pythonw.exe" trick is gone.

Usage
-----
    python scripts/make_launcher_shim.py \
        --runtime <payload>/runtime/python \
        --launcher-exe /path/to/venvlauncher.exe \
        --launcher-exe-gui /path/to/venvwlauncher.exe

``--launcher-exe`` files can be extracted from any CPython Windows distribution, e.g.

    python -c "import zipfile;zipfile.ZipFile('python-3.13.9-amd64.zip').extract(
        'Lib/venv/scripts/nt/venvlauncher.exe', 'out/')"
"""

from __future__ import annotations

import argparse
import struct
import sys
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = PROJECT_ROOT / "dist" / "omniforge-bootstrap" / "runtime" / "python"

SHIM_NAME = "OmniForge.exe"
DEBUG_SHIM_NAME = "OmniForge-Debug.exe"
CMD_NAME = "OmniForge.cmd"
ENTRY_SCRIPT = "omniforge.py"

#: ``venvlauncher.exe`` trailer format (CPython ``PC/launcher.c``): the launcher block is
#: ``\n#!<interpreter-path>\n<shebang-ish payload>`` followed by an ``\0`` terminator.
_MAGIC = b"\n#!"

CMD_CONTENT = """@echo off
rem OmniForge launcher (generated by scripts/make_launcher_shim.py)
rem Starts the app with the bundled embeddable interpreter; %* forwards CLI flags.
setlocal
set "APP_DIR=%~dp0..\\.."
if exist "%APP_DIR%\\venv\\Scripts\\python.exe" (
  "%APP_DIR%\\venv\\Scripts\\python.exe" "%APP_DIR%\\omniforge.py" %*
) else (
  "%~dp0python.exe" "%APP_DIR%\\omniforge.py" %*
)
"""


def log(msg: str) -> None:
    """Progress line."""
    print(f"[launcher] {msg}", flush=True)


def pe_info(path: Path) -> dict[str, object]:
    """Read minimal PE metadata (arch + subsystem) to validate a candidate launcher."""
    data = path.read_bytes()
    if data[:2] != b"MZ":
        raise ValueError(f"{path.name} is not a PE file")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe : pe + 4] != b"PE\0\0":
        raise ValueError(f"{path.name} has no PE signature")
    machine = struct.unpack_from("<H", data, pe + 4)[0]
    subsystem = struct.unpack_from("<H", data, pe + 4 + 20 + 68)[0]
    return {
        "size": len(data),
        "machine": hex(machine),
        "x64": machine == 0x8664,
        "gui": subsystem == 2,
        "console": subsystem == 3,
    }


def build_launcher_block(interpreter: str, script: str, args: str = "") -> bytes:
    """Encode the launcher trailer that ``venvlauncher.exe`` appends to itself.

    Layout (CPython ``PC/launcher.c``, ``process()``)::

        b"\\n#!" + interpreter + b"\\n" + script + b"\\n" + args + b"\\0"
    """
    block = _MAGIC + interpreter.encode("utf-8") + b"\n" + script.encode("utf-8") + b"\n"
    if args:
        block += args.encode("utf-8") + b"\n"
    return block + b"\0"


def make_shim(
    launcher: Path,
    target: Path,
    *,
    interpreter: str,
    script: str,
    args: str = "",
) -> dict[str, object]:
    """Write ``target`` = launcher image + launcher block."""
    info = pe_info(launcher)
    if not info["x64"]:
        raise ValueError(f"{launcher.name} is not an x64 image")
    payload = launcher.read_bytes() + build_launcher_block(interpreter, script, args)
    target.write_bytes(payload)
    log(f"{target.name}: {launcher.name} + launcher block ({len(payload) / 1024:.0f} KB, "
        f"{'GUI' if info['gui'] else 'console'})")
    return {"path": str(target), "size_kb": round(len(payload) / 1024), "gui": info["gui"]}


def find_launcher_sources(explicit_exe: Path | None, explicit_gui: Path | None, python_zip: Path | None) -> tuple[Path | None, Path | None]:
    """Locate ``venvlauncher.exe`` / ``venvwlauncher.exe`` (explicit paths or inside a distro zip)."""
    console = explicit_exe if explicit_exe and explicit_exe.is_file() else None
    gui = explicit_gui if explicit_gui and explicit_gui.is_file() else None
    if python_zip and python_zip.is_file() and (console is None or gui is None):
        cache = python_zip.parent / "_launchers"
        cache.mkdir(exist_ok=True)
        with zipfile.ZipFile(python_zip) as archive:
            for member, dest in (
                ("Lib/venv/scripts/nt/venvlauncher.exe", cache / "venvlauncher.exe"),
                ("Lib/venv/scripts/nt/venvwlauncher.exe", cache / "venvwlauncher.exe"),
            ):
                if member in archive.namelist() and not dest.is_file():
                    with archive.open(member) as src, dest.open("wb") as out:
                        out.write(src.read())
        console = console or (cache / "venvlauncher.exe") if (cache / "venvlauncher.exe").is_file() else console
        gui = gui or (cache / "venvwlauncher.exe") if (cache / "venvwlauncher.exe").is_file() else gui
    return console, gui


def build(
    out_dir: Path,
    *,
    console_launcher: Path | None,
    gui_launcher: Path | None,
    dry_run: bool = False,
) -> dict[str, object]:
    """Emit the shims + the .cmd fallback into ``out_dir`` (normally ``runtime\\python``)."""
    result: dict[str, object] = {"out_dir": str(out_dir)}

    if dry_run:
        log(f"[dry-run] console launcher: {console_launcher}")
        log(f"[dry-run] gui launcher    : {gui_launcher}")
        log(f"[dry-run] target dir      : {out_dir}")
        return result

    out_dir.mkdir(parents=True, exist_ok=True)
    interpreter = "%APP_DIR%\\runtime\\python\\python.exe"
    script = "%APP_DIR%\\" + ENTRY_SCRIPT

    if gui_launcher is not None:
        result["gui"] = make_shim(
            gui_launcher, out_dir / SHIM_NAME,
            interpreter=interpreter, script=script, args="--mode full",
        )
    if console_launcher is not None:
        result["console"] = make_shim(
            console_launcher, out_dir / DEBUG_SHIM_NAME,
            interpreter=interpreter, script=script, args="--mode full",
        )

    cmd_path = out_dir / CMD_NAME
    cmd_path.write_text(CMD_CONTENT, encoding="utf-8")
    result["cmd"] = str(cmd_path)

    if gui_launcher is None and console_launcher is None:
        log("NO launcher images supplied -> shipped .cmd fallback only.")
        log("  fix: pass --launcher-exe/--launcher-exe-gui (venvlauncher.exe), or")
        log("       build with PyInstaller: build_exe.bat --onedir + ISCC /DLaunchMode=exe")
        result["mode"] = "cmd-fallback"
    else:
        result["mode"] = "exe"
    return result


def build_parser() -> argparse.ArgumentParser:
    """CLI."""
    parser = argparse.ArgumentParser(prog="make_launcher_shim", description=__doc__.splitlines()[0])
    parser.add_argument("--runtime", default=str(DEFAULT_OUT), help="Directory to write the launcher into")
    parser.add_argument("--launcher-exe", default=None, help="venvlauncher.exe (console flavour)")
    parser.add_argument("--launcher-exe-gui", default=None, help="venvwlauncher.exe (GUI flavour)")
    parser.add_argument("--python-zip", default=None, help="CPython win-amd64 zip to extract launchers from")
    parser.add_argument("--dry-run", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Entry point."""
    args = build_parser().parse_args(argv)
    console, gui = find_launcher_sources(
        Path(args.launcher_exe) if args.launcher_exe else None,
        Path(args.launcher_exe_gui) if args.launcher_exe_gui else None,
        Path(args.python_zip) if args.python_zip else None,
    )
    result = build(Path(args.runtime), console_launcher=console, gui_launcher=gui, dry_run=args.dry_run)
    log(f"mode: {result.get('mode', 'dry-run')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
